        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'Created'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, SOURCE=src.SOURCE, IMPORT_ID=src.IMPORT_ID, ACTIVITY_AT=src.ACTIVITY_AT,
        DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED, CREATED_BY=src.CREATED_BY, ORGANIZATION_ID=src.ORGANIZATION_ID,
        UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, USER_ID, USER_NAME, SOURCE, IMPORT_ID, ACTIVITY_AT, DATE_CREATED, DATE_UPDATED, CREATED_BY, ORGANIZATION_ID,
        INSERT_DATE, UPDATE_DATE, MD5_HASH
