            ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED, ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED,
            ACTIVITY_JSON:created_by::STRING AS CREATED_BY, ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
            MD5(ACTIVITY_JSON::STRING) AS MD5_HASH
        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'SMS'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, CONTACT_ID=src.CONTACT_ID, USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, DIRECTION=src.DIRECTION, STATUS=src.STATUS,
        TEXT=src.TEXT, LOCAL_PHONE=src.LOCAL_PHONE, REMOTE_PHONE=src.REMOTE_PHONE, TEMPLATE_ID=src.TEMPLATE_ID, SEQUENCE_ID=src.SEQUENCE_ID,
        SEQUENCE_NAME=src.SEQUENCE_NAME, ERROR_MESSAGE=src.ERROR_MESSAGE, DATE_SENT=src.DATE_SENT, ACTIVITY_AT=src.ACTIVITY_AT,
        DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED, CREATED_BY=src.CREATED_BY, ORGANIZATION_ID=src.ORGANIZATION_ID,
        UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, CONTACT_ID, USER_ID, USER_NAME, DIRECTION, STATUS, TEXT, LOCAL_PHONE, REMOTE_PHONE, TEMPLATE_ID, SEQUENCE_ID,
        SEQUENCE_NAME, ERROR_MESSAGE, DATE_SENT, ACTIVITY_AT, DATE_CREATED, DATE_UPDATED, CREATED_BY, ORGANIZATION_ID, INSERT_DATE, UPDATE_DATE, MD5_HASH
    ) VALUES (
        src.ACTIVITY_ID, src.LEAD_ID, src.CONTACT_ID, src.USER_ID, src.USER_NAME, src.DIRECTION, src.STATUS, src.TEXT, src.LOCAL_PHONE, src.REMOTE_PHONE,
        src.TEMPLATE_ID, src.SEQUENCE_ID, src.SEQUENCE_NAME, src.ERROR_MESSAGE, src.DATE_SENT, src.ACTIVITY_AT, src.DATE_CREATED, src.DATE_UPDATED,
        src.CREATED_BY, src.ORGANIZATION_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), src.MD5_HASH
    );

    MERGE INTO SILVER.MEETINGS tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:contact_id::STRING AS CONTACT_ID, ACTIVITY_JSON:user_id::STRING AS USER_ID,
            ACTIVITY_JSON:user_name::STRING AS USER_NAME, ACTIVITY_JSON:title::STRING AS TITLE, ACTIVITY_JSON:status::STRING AS STATUS,
            ACTIVITY_JSON:source::STRING AS SOURCE, ACTIVITY_JSON:note::STRING AS NOTE, ACTIVITY_JSON:location::STRING AS LOCATION,
            ACTIVITY_JSON:starts_at::TIMESTAMP_NTZ AS STARTS_AT, ACTIVITY_JSON:ends_at::TIMESTAMP_NTZ AS ENDS_AT, ACTIVITY_JSON:duration::NUMBER AS DURATION,
            ACTIVITY_JSON:actual_duration::NUMBER AS ACTUAL_DURATION, ACTIVITY_JSON:is_recurring::BOOLEAN AS IS_RECURRING, ACTIVITY_JSON:attendees AS ATTENDEES,
            ACTIVITY_JSON:calendar_event_uids AS CALENDAR_EVENT_UIDS, ACTIVITY_JSON:provider_calendar_type::STRING AS PROVIDER_CALENDAR_TYPE,
            ACTIVITY_JSON:outcome_id::STRING AS OUTCOME_ID, ACTIVITY_JSON:outcome_reason::STRING AS OUTCOME_REASON, ACTIVITY_JSON:activity_at::TIMESTAMP_NTZ AS ACTIVITY_AT,
            ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED, ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED,
            ACTIVITY_JSON:created_by::STRING AS CREATED_BY, ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
            MD5(ACTIVITY_JSON::STRING) AS MD5_HASH
        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'Meeting'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, CONTACT_ID=src.CONTACT_ID, USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, TITLE=src.TITLE, STATUS=src.STATUS,
        SOURCE=src.SOURCE, NOTE=src.NOTE, LOCATION=src.LOCATION, STARTS_AT=src.STARTS_AT, ENDS_AT=src.ENDS_AT, DURATION=src.DURATION,
        ACTUAL_DURATION=src.ACTUAL_DURATION, IS_RECURRING=src.IS_RECURRING, ATTENDEES=src.ATTENDEES, CALENDAR_EVENT_UIDS=src.CALENDAR_EVENT_UIDS,
        PROVIDER_CALENDAR_TYPE=src.PROVIDER_CALENDAR_TYPE, OUTCOME_ID=src.OUTCOME_ID, OUTCOME_REASON=src.OUTCOME_REASON, ACTIVITY_AT=src.ACTIVITY_AT,
        DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED, CREATED_BY=src.CREATED_BY, ORGANIZATION_ID=src.ORGANIZATION_ID,
        UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, CONTACT_ID, USER_ID, USER_NAME, TITLE, STATUS, SOURCE, NOTE, LOCATION, STARTS_AT, ENDS_AT, DURATION, ACTUAL_DURATION,
        IS_RECURRING, ATTENDEES, CALENDAR_EVENT_UIDS, PROVIDER_CALENDAR_TYPE, OUTCOME_ID, OUTCOME_REASON, ACTIVITY_AT, DATE_CREATED, DATE_UPDATED,
        CREATED_BY, ORGANIZATION_ID, INSERT_DATE, UPDATE_DATE, MD5_HASH
    ) VALUES (
        src.ACTIVITY_ID, src.LEAD_ID, src.CONTACT_ID, src.USER_ID, src.USER_NAME, src.TITLE, src.STATUS, src.SOURCE, src.NOTE, src.LOCATION,
        src.STARTS_AT, src.ENDS_AT, src.DURATION, src.ACTUAL_DURATION, src.IS_RECURRING, src.ATTENDEES, src.CALENDAR_EVENT_UIDS,
        src.PROVIDER_CALENDAR_TYPE, src.OUTCOME_ID, src.OUTCOME_REASON, src.ACTIVITY_AT, src.DATE_CREATED, src.DATE_UPDATED,
        src.CREATED_BY, src.ORGANIZATION_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), src.MD5_HASH
    );

    MERGE INTO SILVER.NOTES tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:contact_id::STRING AS CONTACT_ID, ACTIVITY_JSON:user_id::STRING AS USER_ID,
            ACTIVITY_JSON:user_name::STRING AS USER_NAME, ACTIVITY_JSON:note::STRING AS NOTE, ACTIVITY_JSON:note_html::STRING AS NOTE_HTML,
            ACTIVITY_JSON:title::STRING AS TITLE, ACTIVITY_JSON:pinned::BOOLEAN AS PINNED, ACTIVITY_JSON:activity_at::TIMESTAMP_NTZ AS ACTIVITY_AT,
            ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED, ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED,
            ACTIVITY_JSON:created_by::STRING AS CREATED_BY, ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
            MD5(ACTIVITY_JSON::STRING) AS MD5_HASH
        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'Note'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, CONTACT_ID=src.CONTACT_ID, USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, NOTE=src.NOTE, NOTE_HTML=src.NOTE_HTML,
        TITLE=src.TITLE, PINNED=src.PINNED, ACTIVITY_AT=src.ACTIVITY_AT, DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED,
        CREATED_BY=src.CREATED_BY, ORGANIZATION_ID=src.ORGANIZATION_ID, UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, CONTACT_ID, USER_ID, USER_NAME, NOTE, NOTE_HTML, TITLE, PINNED, ACTIVITY_AT, DATE_CREATED, DATE_UPDATED,
        CREATED_BY, ORGANIZATION_ID, INSERT_DATE, UPDATE_DATE, MD5_HASH
    ) VALUES (
        src.ACTIVITY_ID, src.LEAD_ID, src.CONTACT_ID, src.USER_ID, src.USER_NAME, src.NOTE, src.NOTE_HTML, src.TITLE, src.PINNED, src.ACTIVITY_AT,
        src.DATE_CREATED, src.DATE_UPDATED, src.CREATED_BY, src.ORGANIZATION_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), src.MD5_HASH
    );

    MERGE INTO SILVER.LEAD_MERGES tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:destination_lead_id::STRING AS DESTINATION_LEAD_ID,
            ACTIVITY_JSON:destination_display_name::STRING AS DESTINATION_DISPLAY_NAME, ACTIVITY_JSON:source_lead_id::STRING AS SOURCE_LEAD_ID,
            ACTIVITY_JSON:source_display_name::STRING AS SOURCE_DISPLAY_NAME, ACTIVITY_JSON:merge_status::STRING AS MERGE_STATUS,
            ACTIVITY_JSON:error_message::STRING AS ERROR_MESSAGE, ACTIVITY_JSON:user_id::STRING AS USER_ID, ACTIVITY_JSON:user_name::STRING AS USER_NAME,
            ACTIVITY_JSON:activity_at::TIMESTAMP_NTZ AS ACTIVITY_AT, ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED,
            ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED, ACTIVITY_JSON:created_by::STRING AS CREATED_BY,
            ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
            MD5(ACTIVITY_JSON::STRING) AS MD5_HASH
        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'LeadMerge'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, DESTINATION_LEAD_ID=src.DESTINATION_LEAD_ID, DESTINATION_DISPLAY_NAME=src.DESTINATION_DISPLAY_NAME,
        SOURCE_LEAD_ID=src.SOURCE_LEAD_ID, SOURCE_DISPLAY_NAME=src.SOURCE_DISPLAY_NAME, MERGE_STATUS=src.MERGE_STATUS, ERROR_MESSAGE=src.ERROR_MESSAGE,
        USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, ACTIVITY_AT=src.ACTIVITY_AT, DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED,
        CREATED_BY=src.CREATED_BY, ORGANIZATION_ID=src.ORGANIZATION_ID, UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, DESTINATION_LEAD_ID, DESTINATION_DISPLAY_NAME, SOURCE_LEAD_ID, SOURCE_DISPLAY_NAME, MERGE_STATUS, ERROR_MESSAGE,
        USER_ID, USER_NAME, ACTIVITY_AT, DATE_CREATED, DATE_UPDATED, CREATED_BY, ORGANIZATION_ID, INSERT_DATE, UPDATE_DATE, MD5_HASH
    ) VALUES (
        src.ACTIVITY_ID, src.LEAD_ID, src.DESTINATION_LEAD_ID, src.DESTINATION_DISPLAY_NAME, src.SOURCE_LEAD_ID, src.SOURCE_DISPLAY_NAME,
        src.MERGE_STATUS, src.ERROR_MESSAGE, src.USER_ID, src.USER_NAME, src.ACTIVITY_AT, src.DATE_CREATED, src.DATE_UPDATED, src.CREATED_BY,
        src.ORGANIZATION_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), src.MD5_HASH
    );

    MERGE INTO SILVER.LEAD_CREATED_EVENTS tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:user_id::STRING AS USER_ID, ACTIVITY_JSON:user_name::STRING AS USER_NAME,
            ACTIVITY_JSON:source::STRING AS SOURCE, ACTIVITY_JSON:import_id::STRING AS IMPORT_ID, ACTIVITY_JSON:activity_at::TIMESTAMP_NTZ AS ACTIVITY_AT,
            ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED, ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED,
            ACTIVITY_JSON:created_by::STRING AS CREATED_BY, ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
