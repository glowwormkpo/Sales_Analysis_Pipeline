            SELECT LEAD_ID, ACTIVITY_ID, MAX(ACTIVITY_AT) AS ACTIVITY_AT, OBJECT_AGG(FIELD_NAME, RESOLVED_VALUE) AS WRAPPED_ACTIVITIES
            FROM resolved_fields
            GROUP BY LEAD_ID, ACTIVITY_ID
        )
        SELECT LEAD_ID, ACTIVITY_ID, ACTIVITY_AT, WRAPPED_ACTIVITIES, MD5(TO_VARCHAR(WRAPPED_ACTIVITIES)) AS MD5_HASH
        FROM aggregated
