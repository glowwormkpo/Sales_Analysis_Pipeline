/* =============================================================================
   Sales Analytics Pipeline - Phase 4 (Real Data) - Requirements Audit Fixes
   20_silver_refresh_procedure_v2.sql

   Supersedes 17_silver_refresh_procedure.sql. Fixes gap #1 from the
   requirements audit: Section 4.1 explicitly requires "Use upserts (insert
   new, update existing) into warehouse tables" via MERGE INTO with
   MD5_HASH-based change detection and INSERT_DATE/UPDATE_DATE
   auditability. The prior version used TRUNCATE + INSERT (a full rebuild)
   for the real-data backfill, which worked but wasn't a real upsert and
   didn't preserve row-level history the way MERGE does (a row that stops
   appearing in Bronze simply stays untouched in Silver instead of being
   wiped and reinserted with a fresh INSERT_DATE).

   Every table load below now follows the same MERGE pattern used in the
   Phase 3 synthetic pipeline (06_silver_merge_dedup.sql):
     WHEN MATCHED AND MD5_HASH changed  -> UPDATE, refresh UPDATE_DATE
     WHEN NOT MATCHED                   -> INSERT, set both audit dates

   Also folds in two smaller requirements-audit fixes:
     - Gap #7 (dedup key): ALL_ACTIVITIES_TRANSIENT now partitions by
       (LEAD_ID, ACTIVITY_ID) instead of ACTIVITY_ID alone, and orders by
       ACTIVITY_AT first (per the literal spec: "keep the latest activity
       record using activity_at"), then DATE_UPDATED/INSERT_DATE as
       tiebreakers. Note: activity_at is fixed at creation and identical
       across every re-delivered snapshot of the same activity, so it can't
       actually distinguish between snapshots on its own -- DATE_UPDATED
       remains the real tiebreaker in practice, this just satisfies the
       literal spec wording without changing behavior.
     - Gap #3 (partial): CUSTOM_ACTIVITY_TYPES now also carries IS_ARCHIVED,
       CREATED_BY, UPDATED_BY, DATE_CREATED, DATE_UPDATED (added via ALTER
       TABLE below). DESCRIPTION is still intentionally left out -- see the
       existing comment in 12_silver_dictionary_and_users_load.sql on why
       that field can't be safely parsed without corrupting the rest of the
       document.
     - Gap #5: CONTACTS now also carries URLS (confirmed present on real
       contact records from an earlier sample, never mapped before).

   Does NOT yet include: "New Sale [Custom Payment Plan]" in SALES_DETAILS
   (gap #2) or role/status on CLOSE_CRM_USERS_PROCESSED (gap #4) -- both
   pending confirmation of real field names/values (see conversation).
   ============================================================================= */

