CREATE OR REPLACE PROCEDURE SILVER.REFRESH_ALL_REAL_DATA()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    -- =========================================================================
    -- 1. Mixed activity stream: dedupe (per gap #7) + type-specific MERGEs
    -- =========================================================================
    CREATE OR REPLACE TRANSIENT TABLE SILVER.ALL_ACTIVITIES_TRANSIENT AS
    SELECT
        f.value:id::STRING      AS ACTIVITY_ID,
        f.value:_type::STRING   AS ACTIVITY_TYPE,
        f.value:lead_id::STRING AS LEAD_ID,
        f.value                 AS ACTIVITY_JSON,
        b.INSERT_DATE            AS SOURCE_INSERT_DATE
    FROM BRONZE.LEAD_ACTIVITIES_RAW b,
         LATERAL FLATTEN(input => b.JSON_OBJECT:data) f
    -- CORRECTION (confirmed 2026-08-26): this used to partition by
    -- (LEAD_ID, ACTIVITY_ID) per the literal gap #7 spec wording, but every
    -- downstream per-type MERGE (CALLS, MEETINGS, NOTES, SMS_MESSAGES,
    -- LEAD_ACTIVITIES_PROCESSED, etc.) matches ON tgt.ACTIVITY_ID =
    -- src.ACTIVITY_ID alone. If the same ACTIVITY_ID legitimately appears
    -- under two different LEAD_IDs (confirmed happens in real data -- e.g.
    -- a calendar Meeting activity re-delivered against a different lead_id
    -- across snapshots), the old partition kept both rows, and every
    -- downstream MERGE failed with "Duplicate row detected during DML
    -- action" the moment it hit one. ACTIVITY_ID is Close CRM's true
    -- unique identifier for an activity; LEAD_ID is an attribute of it,
    -- not part of its identity. Partitioning by ACTIVITY_ID alone (still
    -- ordered by activity_at/date_updated/insert_date to pick the latest
    -- snapshot) matches what every downstream merge already assumes.
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY f.value:id::STRING
        ORDER BY f.value:activity_at::TIMESTAMP_NTZ DESC NULLS LAST,
                 f.value:date_updated::TIMESTAMP_NTZ DESC NULLS LAST,
                 b.INSERT_DATE DESC
    ) = 1;

    MERGE INTO SILVER.CALLS tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:contact_id::STRING AS CONTACT_ID, ACTIVITY_JSON:user_id::STRING AS USER_ID,
            ACTIVITY_JSON:user_name::STRING AS USER_NAME, ACTIVITY_JSON:direction::STRING AS DIRECTION, ACTIVITY_JSON:status::STRING AS STATUS,
            ACTIVITY_JSON:disposition::STRING AS DISPOSITION, ACTIVITY_JSON:duration::NUMBER AS DURATION, ACTIVITY_JSON:recording_duration::NUMBER AS RECORDING_DURATION,
            ACTIVITY_JSON:phone::STRING AS PHONE, ACTIVITY_JSON:local_phone::STRING AS LOCAL_PHONE, ACTIVITY_JSON:remote_phone::STRING AS REMOTE_PHONE,
            ACTIVITY_JSON:note::STRING AS NOTE, ACTIVITY_JSON:outcome_id::STRING AS OUTCOME_ID, ACTIVITY_JSON:outcome_reason::STRING AS OUTCOME_REASON,
            ACTIVITY_JSON:outcome_autofill_reasoning::STRING AS OUTCOME_AUTOFILL_REASONING, ACTIVITY_JSON:outcome_autofill_confidence::STRING AS OUTCOME_AUTOFILL_CONFIDENCE,
            ACTIVITY_JSON:has_recording::BOOLEAN AS HAS_RECORDING, ACTIVITY_JSON:recording_url::STRING AS RECORDING_URL, ACTIVITY_JSON:call_method::STRING AS CALL_METHOD,
            ACTIVITY_JSON:source::STRING AS SOURCE, ACTIVITY_JSON:cost::STRING AS COST, ACTIVITY_JSON:activity_at::TIMESTAMP_NTZ AS ACTIVITY_AT,
            ACTIVITY_JSON:date_answered::TIMESTAMP_NTZ AS DATE_ANSWERED, ACTIVITY_JSON:date_created::TIMESTAMP_NTZ AS DATE_CREATED,
            ACTIVITY_JSON:date_updated::TIMESTAMP_NTZ AS DATE_UPDATED, ACTIVITY_JSON:created_by::STRING AS CREATED_BY, ACTIVITY_JSON:created_by_name::STRING AS CREATED_BY_NAME,
            ACTIVITY_JSON:organization_id::STRING AS ORGANIZATION_ID,
            MD5(ACTIVITY_JSON::STRING) AS MD5_HASH
        FROM SILVER.ALL_ACTIVITIES_TRANSIENT
        WHERE ACTIVITY_TYPE = 'Call'
    ) src
    ON tgt.ACTIVITY_ID = src.ACTIVITY_ID
    WHEN MATCHED AND tgt.MD5_HASH != src.MD5_HASH THEN UPDATE SET
        LEAD_ID=src.LEAD_ID, CONTACT_ID=src.CONTACT_ID, USER_ID=src.USER_ID, USER_NAME=src.USER_NAME, DIRECTION=src.DIRECTION, STATUS=src.STATUS,
        DISPOSITION=src.DISPOSITION, DURATION=src.DURATION, RECORDING_DURATION=src.RECORDING_DURATION, PHONE=src.PHONE, LOCAL_PHONE=src.LOCAL_PHONE,
        REMOTE_PHONE=src.REMOTE_PHONE, NOTE=src.NOTE, OUTCOME_ID=src.OUTCOME_ID, OUTCOME_REASON=src.OUTCOME_REASON,
        OUTCOME_AUTOFILL_REASONING=src.OUTCOME_AUTOFILL_REASONING, OUTCOME_AUTOFILL_CONFIDENCE=src.OUTCOME_AUTOFILL_CONFIDENCE,
        HAS_RECORDING=src.HAS_RECORDING, RECORDING_URL=src.RECORDING_URL, CALL_METHOD=src.CALL_METHOD, SOURCE=src.SOURCE, COST=src.COST,
        ACTIVITY_AT=src.ACTIVITY_AT, DATE_ANSWERED=src.DATE_ANSWERED, DATE_CREATED=src.DATE_CREATED, DATE_UPDATED=src.DATE_UPDATED,
        CREATED_BY=src.CREATED_BY, CREATED_BY_NAME=src.CREATED_BY_NAME, ORGANIZATION_ID=src.ORGANIZATION_ID,
        UPDATE_DATE=CURRENT_TIMESTAMP(), MD5_HASH=src.MD5_HASH
    WHEN NOT MATCHED THEN INSERT (
        ACTIVITY_ID, LEAD_ID, CONTACT_ID, USER_ID, USER_NAME, DIRECTION, STATUS, DISPOSITION, DURATION, RECORDING_DURATION, PHONE, LOCAL_PHONE,
        REMOTE_PHONE, NOTE, OUTCOME_ID, OUTCOME_REASON, OUTCOME_AUTOFILL_REASONING, OUTCOME_AUTOFILL_CONFIDENCE, HAS_RECORDING, RECORDING_URL,
        CALL_METHOD, SOURCE, COST, ACTIVITY_AT, DATE_ANSWERED, DATE_CREATED, DATE_UPDATED, CREATED_BY, CREATED_BY_NAME, ORGANIZATION_ID,
        INSERT_DATE, UPDATE_DATE, MD5_HASH
    ) VALUES (
        src.ACTIVITY_ID, src.LEAD_ID, src.CONTACT_ID, src.USER_ID, src.USER_NAME, src.DIRECTION, src.STATUS, src.DISPOSITION, src.DURATION, src.RECORDING_DURATION,
        src.PHONE, src.LOCAL_PHONE, src.REMOTE_PHONE, src.NOTE, src.OUTCOME_ID, src.OUTCOME_REASON, src.OUTCOME_AUTOFILL_REASONING, src.OUTCOME_AUTOFILL_CONFIDENCE,
        src.HAS_RECORDING, src.RECORDING_URL, src.CALL_METHOD, src.SOURCE, src.COST, src.ACTIVITY_AT, src.DATE_ANSWERED, src.DATE_CREATED, src.DATE_UPDATED,
        src.CREATED_BY, src.CREATED_BY_NAME, src.ORGANIZATION_ID, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), src.MD5_HASH
    );

    MERGE INTO SILVER.SMS_MESSAGES tgt
    USING (
        SELECT
            ACTIVITY_ID,
            ACTIVITY_JSON:lead_id::STRING AS LEAD_ID, ACTIVITY_JSON:contact_id::STRING AS CONTACT_ID, ACTIVITY_JSON:user_id::STRING AS USER_ID,
            ACTIVITY_JSON:user_name::STRING AS USER_NAME, ACTIVITY_JSON:direction::STRING AS DIRECTION, ACTIVITY_JSON:status::STRING AS STATUS,
            ACTIVITY_JSON:text::STRING AS TEXT, ACTIVITY_JSON:local_phone::STRING AS LOCAL_PHONE, ACTIVITY_JSON:remote_phone::STRING AS REMOTE_PHONE,
